#!/usr/bin/env node
// Test stack publisher of the dotnet pack, for an application composed by an Aspire AppHost: the compose file
// is generated from the AppHost's real resource graph, never written by hand. Configure it as
//
//   "stack": { "publish": "node {packs}/dotnet/stack/aspire-publish.mjs --out {out}" }
//
// It runs `aspire publish` (the Aspire CLI at the AppHost SDK's own version, through `dotnet dnx`, so nothing is
// installed globally) with TestStack=true, which the AppHost's test-stack hook turns into a Docker Compose
// environment (packs/dotnet/stack/teststack-hook.md). Because the AppHost is executed, every form of wiring is
// covered: conditional blocks, extension methods, callbacks, image tags, ports.
//
// The published file is then adjusted by the declared test-only overrides in `.factory/app.json`
// (`stack.publishOverrides`), each with the reason the test stack needs it:
//
//   "publishOverrides": {
//     "name": "shop-teststack",                                   // compose project name
//     "parameters": { "*_PORT": { "value": "8080", "why": "..." } },  // ${NAME} the AppHost leaves to deployment
//     "remove": { "<service>": "why" },
//     "ports": { "why": "...", "services": { "<service>": "<stack.ports key>" } },  // slot host ports
//     "services": [
//       { "services": "*" | ["a", "b"], "why": "...",
//         "ports": "<stack.ports key>",          // publish the primary port on the slot's host port variable
//         "env": { "K": "v" },                   // replace a variable the AppHost sets (fails if it does not)
//         "addEnv": { "K": "v" },                // add a variable the AppHost does not set (fails if it does)
//         "set": { "restart": "unless-stopped" } } // other compose keys
//     ]
//   }
//
// An override that no longer applies (a service, variable or parameter the AppHost dropped or now sets itself)
// fails the publish, and so does any ${PARAMETER} left without a value: the AppHost changed and the test stack
// needs a decision. `factory teststack publish` writes the file; `factory teststack drift` (publish --check)
// fails when the committed file differs from what the AppHost publishes now.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';

export const HEADER = (appHost) => `# Generated by \`factory teststack publish\` from ${appHost} (aspire publish, TestStack=true) and the
# declared test-only overrides in .factory/app.json (stack.publishOverrides). Do not edit: change the AppHost or
# the overrides and publish again. \`factory teststack drift\` fails when this file is out of date.
`;

/** The AppHost project: `stack.publishAppHost`, or the one project using Aspire.AppHost.Sdk outside test folders. */
export function findAppHost(root, configured) {
  if (configured) return path.resolve(root, configured);
  const hits = [];
  const walk = (dir, depth) => {
    if (depth > 4) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.name.startsWith('.') || ['node_modules', 'bin', 'obj', 'artifacts'].includes(e.name)) continue;
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p, depth + 1);
      else if (e.name.endsWith('.csproj') && /Aspire\.AppHost\.Sdk/.test(fs.readFileSync(p, 'utf8')) && !/Tests?\.csproj$/i.test(e.name) && !/(^|[\\/])tests?([\\/]|$)/i.test(path.relative(root, dir))) hits.push(p);
    }
  };
  walk(root, 0);
  if (hits.length !== 1) throw new Error(hits.length ? `several AppHost projects (${hits.map((h) => path.relative(root, h)).join(', ')}): set stack.publishAppHost` : 'no Aspire AppHost project found: this publisher needs one');
  return hits[0];
}

/** The Aspire version the AppHost is built with (its SDK), so the CLI matches it. */
export function aspireVersion(csproj) {
  const m = /Aspire\.AppHost\.Sdk\/([\w.+-]+)/.exec(fs.readFileSync(csproj, 'utf8'));
  if (!m) throw new Error(`${csproj} does not name an Aspire.AppHost.Sdk version`);
  return m[1];
}

const why = (entry, where, problems) => {
  if (typeof entry?.why !== 'string' || entry.why.trim().length < 10) problems.push(`${where}: give the reason the test stack needs it ("why")`);
};
const globRe = (glob) => new RegExp(`^${glob.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*')}$`);

/**
 * Applies the declared overrides to a published compose document. Returns { doc, problems }; any problem means
 * the overrides no longer match what the AppHost publishes.
 */
export function transform(published, overrides = {}, stack = {}) {
  const doc = structuredClone(published);
  const problems = [];
  const services = doc.services ?? {};
  if (overrides.name) doc.name = overrides.name;

  for (const [name, reason] of Object.entries(overrides.remove ?? {})) {
    if (!services[name]) problems.push(`remove.${name}: the AppHost publishes no service "${name}"`);
    if (typeof reason !== 'string' || reason.trim().length < 10) problems.push(`remove.${name}: give the reason`);
    delete services[name];
    for (const s of Object.values(services)) {
      if (Array.isArray(s.depends_on)) s.depends_on = s.depends_on.filter((d) => d !== name);
      else if (s.depends_on) delete s.depends_on[name];
    }
  }

  // Slot host ports: { "why": "...", "services": { "<service>": "<stack.ports key>" } }.
  const portEntries = Object.entries(overrides.ports?.services ?? {}).map(([service, key]) => ({ services: [service], ports: key, why: overrides.ports.why }));
  for (const [i, entry] of [...portEntries, ...(overrides.services ?? [])].entries()) {
    const where = i < portEntries.length ? `ports.services.${entry.services[0]}` : `services[${i - portEntries.length}]`;
    why(entry, where, problems);
    const names = entry.services === '*' ? Object.keys(services) : [].concat(entry.services ?? []);
    if (!names.length) problems.push(`${where}: name the services ("*" for all)`);
    for (const name of names) {
      const svc = services[name];
      if (!svc) {
        problems.push(`${where}: the AppHost publishes no service "${name}"`);
        continue;
      }
      svc.environment ??= {};
      for (const [k, v] of Object.entries(entry.env ?? {})) {
        if (!(k in svc.environment)) problems.push(`${where}: "${name}" has no ${k} from the AppHost to replace (use addEnv, or drop the override)`);
        else svc.environment[k] = String(v);
      }
      for (const [k, v] of Object.entries(entry.addEnv ?? {})) {
        if (k in svc.environment) problems.push(`${where}: the AppHost now sets ${k} on "${name}" itself ("${svc.environment[k]}"): drop the override or replace it with env`);
        else svc.environment[k] = String(v);
      }
      if (!Object.keys(svc.environment).length) delete svc.environment;
      for (const [k, v] of Object.entries(entry.set ?? {})) svc[k] = v;
      if (entry.ports) {
        const port = stack.ports?.[entry.ports];
        if (!port?.env) problems.push(`${where}: stack.ports.${entry.ports} is not defined`);
        else {
          const target = [...(svc.ports ?? []), ...(svc.expose ?? [])].map(String).map((p) => p.split(':').pop())[0];
          if (!target) problems.push(`${where}: "${name}" publishes no port to map`);
          else svc.ports = [`\${${port.env}:-${port.base}}:${target}`];
        }
      }
    }
  }

  // Parameters the AppHost leaves to the deployment (${NAME} with no default).
  let text = JSON.stringify(doc);
  const used = new Set();
  for (const [glob, entry] of Object.entries(overrides.parameters ?? {})) {
    why(entry, `parameters.${glob}`, problems);
    const re = globRe(glob);
    text = text.replace(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (m, name) => {
      if (!re.test(name)) return m;
      used.add(glob);
      return String(entry.value);
    });
    if (!used.has(glob)) problems.push(`parameters.${glob}: the AppHost publishes no such parameter`);
  }
  const result = JSON.parse(text);
  // Every ${VARIABLE} left must get a value at `up`: an image the stack builds, a slot port, or stack.env.
  const known = new Set([
    ...Object.values(stack.services ?? {}).map((s) => s?.image?.env).filter(Boolean),
    ...Object.values(stack.ports ?? {}).map((p) => p?.env).filter(Boolean),
    ...Object.keys(stack.env ?? {}),
  ]);
  const unresolved = [...new Set([...text.matchAll(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g)].map((m) => m[1]))].filter((v) => !known.has(v));
  for (const v of unresolved.sort()) problems.push(`\${${v}} has no value: the AppHost added a parameter; give it one in stack.env, or in publishOverrides.parameters with the reason`);
  return { doc: result, problems };
}

export function render(doc, appHost) {
  return HEADER(appHost) + stringify(doc, { lineWidth: 0 });
}

// The Aspire CLI's own notices (a newer version is available, how to update) are not part of a failure.
export const stripCliNotices = (text) => String(text).split('\n').filter((l) => !/A new version of Aspire is available|To update, run: aspire update|aka\.ms\/aspire\/update/.test(l)).join('\n').replace(/\n{3,}/g, '\n\n').trim();

/** Runs `aspire publish` for the AppHost with TestStack=true; returns the published compose document. */
export function aspirePublish(root, csproj, { run = spawnSync, env = process.env } = {}) {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'aspire-publish-'));
  try {
    const version = aspireVersion(csproj);
    const args = ['dnx', '--yes', `aspire.cli@${version}`, '--', 'publish', '--apphost', csproj, '-o', out, '--non-interactive'];
    const r = run('dotnet', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], env: { ...env, TestStack: 'true', DOTNET_CLI_TELEMETRY_OPTOUT: '1', DOTNET_NOLOGO: '1', ASPIRE_CLI_TELEMETRY_OPTOUT: '1' } });
    if (r.status !== 0) throw new Error(`aspire publish failed (${r.status ?? r.error?.message}):\n${stripCliNotices(`${r.stdout ?? ''}${r.stderr ?? ''}`).slice(-3000)}`);
    const file = path.join(out, 'docker-compose.yaml');
    if (!fs.existsSync(file)) throw new Error(`the AppHost published no docker-compose.yaml with TestStack=true: add the test-stack hook to ${path.relative(root, csproj)} (setup-teststack skill; packs/dotnet/stack/teststack-hook.md)`);
    return parse(fs.readFileSync(file, 'utf8'));
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
}

async function main(argv) {
  const i = argv.indexOf('--out');
  if (i < 0 || !argv[i + 1]) throw Object.assign(new Error('usage: aspire-publish.mjs --out <dir>'), { exitCode: 64 });
  const root = process.cwd();
  const here = path.dirname(fileURLToPath(import.meta.url));
  const { repoOverlay } = await import(path.join(here, '../../../scripts/pipeline/lib/config.mjs'));
  const config = repoOverlay(root);
  const stack = config.stack ?? {};
  const csproj = findAppHost(root, stack.publishAppHost);
  const published = aspirePublish(root, csproj);
  const { doc, problems } = transform(published, stack.publishOverrides ?? {}, stack);
  if (problems.length) throw new Error(`the published stack and the declared overrides (stack.publishOverrides) no longer agree:\n- ${problems.join('\n- ')}`);
  const target = path.resolve(root, argv[i + 1]);
  fs.mkdirSync(target, { recursive: true });
  const name = path.basename(stack.composeFile ?? 'docker-compose.yaml');
  fs.writeFileSync(path.join(target, name), render(doc, path.relative(root, csproj)));
  console.error(`aspire-publish: ${Object.keys(doc.services ?? {}).length} service(s) -> ${path.join(argv[i + 1], name)}`);
}

const isMain = (() => {
  try {
    return fs.realpathSync(fileURLToPath(import.meta.url)) === fs.realpathSync(process.argv[1]);
  } catch {
    return false;
  }
})();
if (isMain) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(`aspire-publish: ${error.message}`);
    process.exitCode = error.exitCode ?? 1;
  });
}
