test('the REST hosts (GitLab, Azure DevOps, Bitbucket share it) class a bare 403 on a POST as refused, on a GET as auth', async () => {
  const reply = (status, text, headers = {}) => async () => new Response(text, { status, headers });
  const post = createHttp({ baseUrl: 'https://h', fetch: reply(403, '{"message":"403 Forbidden"}'), retries: 0 });
  await assert.rejects(post.request('POST', '/mr', { body: { title: 'x' } }), (e) => e instanceof HostRefusedError);
  await assert.rejects(post.request('GET', '/mr'), (e) => e instanceof HostAuthError);
  const scoped = createHttp({ baseUrl: 'https://h', fetch: reply(403, '{"message":"insufficient_scope"}'), retries: 0 });
  await assert.rejects(scoped.request('POST', '/mr', { body: { title: 'x' } }), (e) => e instanceof HostAuthError);
  const spam = createHttp({ baseUrl: 'https://h', fetch: reply(400, '{"message":"Your merge request has been recognized as spam"}'), retries: 0 });
  await assert.rejects(spam.request('POST', '/mr', { body: { title: 'x' } }), (e) => e.code === 'refused');
});

