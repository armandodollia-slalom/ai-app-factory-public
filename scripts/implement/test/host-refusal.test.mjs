const GREEN = { state: 'success', names: ['AI app factory'], failing: [], pending: [], rounds: 0 };
function io(order, extra = {}) {
  return {
    analysisGate: () => (order.push('analysis-gate'), { ok: true, results: [] }),
    push: (o) => (order.push(o.commitRecords === false ? 'sync' : 'push'), { pushed: true }),
    repo: () => 'acme/shop',
    gate: async () => (order.push('branch-ci'), GREEN),
    prOpen: () => false,
    publishTicket: () => {},
    assess: () => (order.push('assess'), { severity: 'Low', tickets: [] }),
    publishGate: () => {},
    regate: () => {},
    analyse: async () => {},
    media: () => ({ notes: [] }),
    updateBody: () => {},
    release: () => {},
    ownsPr: () => true,
    stateDecision: async () => {},
    usage: () => [],
    held: () => [],
    ...extra,
  };
}

