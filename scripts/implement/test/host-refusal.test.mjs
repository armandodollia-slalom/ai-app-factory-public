const filterHost = (refused = (b) => b.includes(REFUSED_TEXT)) => {
  const calls = { open: [], comment: [] };
  const host = {
    type: 'github',
    capabilities: { drafts: true },
    pr: {
      open: async (a) => {
        calls.open.push(a);
        if (refused(a.body) || refused(a.title)) throw new HostRefusedError(`gh pr create failed: ${GH_403}`);
        return { number: 7, url: 'https://github.com/acme/shop/pull/7' };
      },
      comment: async (n, text) => {
        calls.comment.push(text);
        if (refused(text)) throw new HostRefusedError(`gh pr comment failed: HTTP 403: 403 Forbidden`);
        return { id: 1 };
      },
    },
  };
  return { host, calls };
};

function tmpRepo() {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'host-refusal-')));
  const g = (...a) => sh('git', a, { cwd: dir, encoding: 'utf8' });
  g('init', '-q', '-b', 'main');
  g('config', 'user.email', 't@example.com');
  g('config', 'user.name', 'T');
  fs.writeFileSync(path.join(dir, '.gitignore'), '.factory/state/\n');
  g('add', '-A');
  g('commit', '-qm', 'init');
  return { dir, config: { root: dir, stateDir: '.factory/state', metricsDir: '.factory/metrics', implement: {}, project: { languages: [] } } };
}

