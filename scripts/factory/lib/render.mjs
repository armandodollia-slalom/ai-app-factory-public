// Line endings do not count: git (text=auto, core.autocrlf) may check a generated file out with other ones.
const sha = (text) => crypto.createHash('sha256').update(String(text).replace(/\r\n/g, '\n')).digest('hex').slice(0, 16);
const readText = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null);
const readJson = (file, fallback = {}) => {
  const text = readText(file);
  if (text == null || !text.trim()) return fallback;
  return JSON.parse(text);
};

export function readPin(root) {
  const pin = readJson(path.join(root, PIN), {});
  return { tools: TOOLS, ...pin, features: { ...FEATURE_DEFAULTS, ...(pin.features ?? {}) } };
}

// ---- blocks --------------------------------------------------------------------------------------

const MARKERS = {
  md: ['<!-- factory:begin (generated by `factory render`; edit outside this block) -->', '<!-- factory:end -->'],
  hash: ['# >>> factory (generated by `factory render`; edit outside this block)', '# <<< factory'],
};
const blockRe = ([begin, end]) => new RegExp(`\\n?${begin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\n[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\n?`);

export function applyBlock(text, style, content) {
  const [begin, end] = MARKERS[style];
  const block = `${begin}\n${content.trim()}\n${end}\n`;
  if (text == null || !text.trim()) return block;
  const re = blockRe(MARKERS[style]);
  if (re.test(text)) return text.replace(re, (m) => `${m.startsWith('\n') ? '\n' : ''}${block}`);
  return `${text.replace(/\n*$/, '\n')}\n${block}`;
}
export function extractBlock(text, style) {
  if (text == null) return null;
  const [begin, end] = MARKERS[style];
  const start = text.indexOf(`${begin}\n`);
  const stop = text.indexOf(end, start);
  return start < 0 || stop < 0 ? null : text.slice(start + begin.length + 1, stop).trim();
}
export function stripBlock(text, style) {
  return text == null ? null : text.replace(blockRe(MARKERS[style]), '\n').replace(/^\n+/, '').replace(/\n{3,}/g, '\n\n');
}

// ---- hook JSON (Claude Code, Codex, Gemini share the shape { hooks: { Event: [{ matcher?, hooks: [{ command }] }] } }) --

const hookOwner = (features) => (command) => /\.factory\/bin\/factory\.mjs/.test(command ?? '') || (features.graphify && /graphify hook-/.test(command ?? ''));

function splitHooks(doc, ours) {
  const owned = {};
  const rest = {};
  for (const [event, entries] of Object.entries(doc?.hooks ?? {})) {
    for (const entry of Array.isArray(entries) ? entries : []) {
      const hooks = Array.isArray(entry.hooks) ? entry.hooks : [];
      const mine = hooks.filter((h) => ours(h.command));
      const theirs = hooks.filter((h) => !ours(h.command));
      if (mine.length) (owned[event] ??= []).push({ ...entry, hooks: mine });
      if (theirs.length || !hooks.length) (rest[event] ??= []).push({ ...entry, hooks: theirs });
    }
  }
  return { owned, rest };
}

function hooksOutput(file, template, features) {
  const ours = hookOwner(features);
  const wanted = splitHooks(template, ours).owned;
  return {
    path: file,
    kind: 'json',
    expected: wanted,
    owned: (doc) => splitHooks(doc, ours).owned,
    apply: (doc) => {
      const { rest } = splitHooks(doc, ours);
      const hooks = { ...rest };
      for (const [event, entries] of Object.entries(wanted)) hooks[event] = [...(hooks[event] ?? []), ...entries];
      return { ...doc, hooks };
    },
    strip: (doc) => {
      const { rest } = splitHooks(doc, ours);
      const out = { ...doc, hooks: rest };
      if (!Object.keys(rest).length) delete out.hooks;
      return out;
    },
  };
}

// Entries of a template that belong to a feature that is off are left out.
function filterTemplate(template, features) {
  const keep = (command) => (features.graphify || !/graphify /.test(command)) && (features.lsp || !/ lsp hook/.test(command));
  const hooks = {};
  for (const [event, entries] of Object.entries(template.hooks ?? {})) {
    const kept = entries.map((e) => ({ ...e, hooks: (e.hooks ?? []).filter((h) => keep(h.command ?? '')) })).filter((e) => e.hooks.length);
    if (kept.length) hooks[event] = kept;
  }
  return { ...template, hooks };
}

// ---- agent files ---------------------------------------------------------------------------------

function parseFrontMatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!m) return { data: {}, body: text };
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if (/^".*"$/.test(v)) v = JSON.parse(v);
    else if (/^'.*'$/.test(v)) v = v.slice(1, -1).replace(/''/g, "'");
    data[kv[1]] = v;
  }
  return { data, body: text.slice(m[0].length) };
}
const yamlValue = (v) => (Array.isArray(v) ? v.join(', ') : typeof v === 'string' && /[:#'"[\]{}]|^\s|\s$/.test(v) ? JSON.stringify(v) : String(v));

// The agents an interactive session can start by name: the factory's base definition plus this
// repository's addendum. The pipeline builds its own prompts (scripts/pipeline/lib/agents.mjs).
function agentOutputs(root, installRoot, pin) {
  const dir = path.join(installRoot, 'agents');
  if (!pin.features.agentFiles || !fs.existsSync(dir)) return [];
  const overrides = readJson(path.join(installRoot, 'scripts', 'agents-claude.json'), {});
  const outputs = [];
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.agent.md')).sort()) {
    const name = file.slice(0, -'.agent.md'.length);
    const override = readText(path.join(root, '.factory/agents', file));
    const { data, body } = parseFrontMatter(override ?? fs.readFileSync(path.join(dir, file), 'utf8'));
    const addendum = addendumText(readText(path.join(root, '.factory/agents', `${name}.md`)));
    const text = [
      body.trim(),
      addendum && `## Project context\n\n${addendum}`,
      `## Lessons\n\nIf \`.factory/lessons/${name}.md\` exists, read it before you start and follow every rule in it. They come from earlier reviews, verifier denials and test failures. (When the pipeline runs this agent it already includes them.)`,
    ].filter(Boolean).join('\n\n');
    const head = (extra) => ['---', '# Generated by `factory render`. Do not edit: change .factory/agents/ (addendum or override) and render again.', `name: ${name}`, `description: ${yamlValue(data.description ?? '')}`, ...extra, '---', ''].join('\n');
    if (pin.tools.includes('claude')) outputs.push({ path: `.claude/agents/${name}.md`, kind: 'file', content: `${head(Object.entries(overrides[name] ?? {}).map(([k, v]) => `${k}: ${yamlValue(v)}`))}\n${text}\n` });
    if (pin.tools.includes('copilot')) outputs.push({ path: `.github/agents/${name}.agent.md`, kind: 'file', content: `${head([])}\n${text}\n` });
  }
  return outputs;
}

