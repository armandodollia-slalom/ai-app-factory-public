const CI_TARGET = {
  // Workflows get a `factory-` prefix so they never collide with the team's own.
  'github-actions': (rel) => `.github/${rel.replace(/^workflows\//, 'workflows/factory-')}`,
  'gitlab-ci': (rel) => `.gitlab/ci/${rel}`,
  'azure-pipelines': (rel) => `.azure-pipelines/${rel}`,
  jenkins: (rel) => `ci/jenkins/${rel}`,
  // CircleCI and Bitbucket Pipelines read one file each: the factory's, or (when the team has its own) a copy next to it.
  circleci: (rel) => `.circleci/${rel}`,
  'bitbucket-pipelines': (rel) => rel,
};
// The CI systems whose definitions call the shared job script (.factory/ci/factory-ci.sh).
const SHARED_SCRIPT = ['jenkins', 'circleci', 'bitbucket-pipelines', 'custom'];
// The one definition file a CI system reads, and where the factory's goes when the team has its own.
const SINGLE_FILE = { circleci: ['.circleci/config.yml', '.circleci/factory.yml'], 'bitbucket-pipelines': ['bitbucket-pipelines.yml', 'bitbucket-pipelines.factory.yml'] };
const GENERATED = /^(#|\/\/) Generated by `factory render`/;
export const GITLAB_ROOT = '.gitlab-ci.yml';
export const GITLAB_INCLUDE = '.gitlab/ci/factory.yml';

// Which template files a repository gets: features, and the tracker's own automations.
function ciWanted(rel, features, tracker) {
  if (!features.graphify && /graphify/.test(rel)) return false;
  if (!features.demoVideo && /demo-video/.test(rel)) return false;
  // GitHub issue events drive these; another tracker is swept on a schedule (tracker-sweep, factory-tracker).
  if (/board-epic-assign|board-escalation-resolve/.test(rel)) return tracker === 'github';
  if (/tracker-sweep/.test(rel)) return Boolean(tracker) && tracker !== 'github';
  if (/factory-tracker/.test(rel)) return Boolean(tracker);
  return true;
}

// The secrets the factory's own commands need beyond the CI system's token: every `${NAME}` in the
// `host` and `tracker` sections (a Jira token, a GitLab token for a GitHub-built repository, ...). GitLab
// exposes CI/CD variables to every job; GitHub Actions and Azure Pipelines need them mapped by name.
export function ciSecretNames(config, provider, used = null) {
  const names = new Set();
  const walk = (v) => {
    if (typeof v === 'string') for (const m of v.matchAll(/\$\{(\w+)\}/g)) names.add(m[1]);
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  };
  walk(config.host);
  walk(config.tracker);
  // GitHub (as the host or the tracker) is reached through `gh`, which reads GH_TOKEN; GitHub Actions has its own.
  if (used && (used.host.type === 'github' || used.tracker.type === 'github')) names.add('GH_TOKEN');
  const native = { 'github-actions': ['GITHUB_TOKEN', 'GH_TOKEN'], 'azure-pipelines': ['AZURE_DEVOPS_TOKEN', 'SYSTEM_ACCESSTOKEN'], 'gitlab-ci': [] }[provider] ?? [];
  return [...names].filter((n) => !native.includes(n)).sort();
}
// How each CI system names a secret in its definition: GitHub Actions and Azure Pipelines map them by name, Jenkins reads
// them from its credentials store (a "secret text" credential whose ID is the name in lower case with dashes); GitLab,
// CircleCI (contexts) and Bitbucket (secured repository variables) expose them to every job.
const SECRET_LINE = { 'github-actions': (n) => `${n}: \${{ secrets.${n} }}`, 'azure-pipelines': (n) => `${n}: $(${n})`, 'gitlab-ci': () => null, jenkins: (n) => `${n} = credentials('${n.toLowerCase().replace(/_/g, '-')}')`, circleci: () => null, 'bitbucket-pipelines': () => null };
export const expandSecrets = (text, provider, names) =>
  text.replace(/^([ \t]*)(?:#|\/\/) factory:secrets\r?\n/gm, (_m, indent) => names.map((n) => SECRET_LINE[provider]?.(n)).filter(Boolean).map((l) => `${indent}${l}\n`).join(''));

// Drops the block a `factory:<feature>` marker line stands before: the next line and every deeper-indented line after
// it (a YAML entry or list item; a Groovy stage up to its closing brace).
export function stripMarked(text, marker) {
  const lines = text.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = new RegExp(`^([ \\t]*)(?:#|//) ${marker}\\s*$`).exec(lines[i]);
    if (!m) {
      out.push(lines[i]);
      continue;
    }
    const indent = m[1].length;
    const first = lines[i + 1] ?? '';
    let j = i + 2;
    const depth = (l) => l.length - l.trimStart().length;
    while (j < lines.length && (lines[j].trim() === '' || depth(lines[j]) > indent)) j++;
    if (/\{\s*$/.test(first) && /^\s*\}\s*$/.test(lines[j] ?? '') && depth(lines[j]) === indent) j++;
    i = j - 1;
  }
  return out.join('\n');
}

// Puts each snippet (the analysis jobs) at its `factory:<name>` marker, indented like it; removes markers left empty.
function fillSnippets(text, snippets) {
  return text.replace(/^([ \t]*)(?:#|\/\/) (factory:analysis[\w-]*)\r?\n/gm, (_m, indent, marker) => (snippets[marker] ? `${snippets[marker].split('\n').map((l) => `${indent}${l}`).join('\n')}\n` : ''));
}

const topLevelKeys = (text) => new Set([...String(text ?? '').matchAll(/^([A-Za-z_][\w-]*)\s*:/gm)].map((m) => m[1]));

// The analysis CI files for this repository's settings and CI system ([] without an analysis section or CI jobs).
export function analysisCiFiles(root, installRoot, provider) {
  let overlay;
  try {
    overlay = repoOverlay(root);
  } catch {
    return [];
  }
  if (!overlay.analysis) return [];
  const config = { ...overlay, root, project: projectModel(root, overlay) };
  return analysisCiOutputs(config, { provider, installRoot, resolved: resolveAnalysis(config, { installRoot }) });
}

// The PR opens finished (implement.preOpen): the gate, analysis and demo-video workflows also run on pushes of the story
// branches, and a PR's run of the same head reuses that run (scripts/factory/lib/pre-open-ci.mjs).
function preOpenCi(provider, target, text, config) {
  if (provider !== 'github-actions' || !PRE_OPEN_WORKFLOWS.includes(target)) return text;
  if (!preOpenSettings(config).enabled) return text;
  const head = /^(# Generated by `factory render`[^\n]*\n)/.exec(text)?.[1] ?? '';
  return `${head}${withBranchRuns(text.slice(head.length), { patterns: storyBranchPatterns(config) })}`;
}

function ciOutputs(root, installRoot, provider, used, features) {
  const dir = path.join(installRoot, 'templates', 'ci', provider);
  if (!fs.existsSync(dir)) return [];
  const config = readJson(path.join(root, '.factory/config.json'), {});
  const names = ciSecretNames(config, provider, used);
  const walk = (rel = '') => fs.readdirSync(path.join(dir, rel), { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(rel, e.name)) : [path.join(rel, e.name).replace(/\\/g, '/')]));
  const out = [];
  const analysis = analysisCiFiles(root, installRoot, provider);
  const snippets = Object.fromEntries(analysis.filter((o) => o.snippet).map((o) => [o.snippet, o.content]));
  for (const rel of walk().sort()) {
    if (!ciWanted(rel, features, used.tracker.type)) continue;
    let text = expandSecrets(fs.readFileSync(path.join(dir, rel), 'utf8'), provider, names);
    if (!features.demoVideo) text = stripMarked(text, 'factory:demo-video');
    if (!features.graphify) text = stripMarked(text, 'factory:graphify');
    text = fillSnippets(text, snippets);
    const comment = /Jenkinsfile/.test(rel) ? '//' : '#';
    let target = CI_TARGET[provider](rel);
    const single = SINGLE_FILE[provider];
    if (single && target === single[0]) {
      // The team's own file (not one the factory generated): the factory's goes next to it, and check says what to merge.
      const own = readText(path.join(root, single[0]));
      if (own != null && !GENERATED.test(own)) {
        target = single[1];
        out.push({ path: target, kind: 'file', content: `${comment} Generated by \`factory render\`. Do not edit.\n${text}`, verify: () => [`${single[0]} is the repository's own: ${provider} reads only that file, so merge the factory's jobs and workflows from ${single[1]} into it (factory check reports this until ${single[0]} names factory-ci.sh)`].filter(() => !/factory-ci\.sh/.test(readText(path.join(root, single[0])) ?? '')) });
        continue;
      }
    }
    out.push({ path: target, kind: 'file', content: `${comment} Generated by \`factory render\`. Do not edit.\n${preOpenCi(provider, target, text, config)}` });
  }
  if (SHARED_SCRIPT.includes(provider)) out.push({ path: '.factory/ci/factory-ci.sh', kind: 'file', content: fs.readFileSync(path.join(installRoot, 'templates/ci/shared/factory-ci.sh'), 'utf8').replace(/^#!\/usr\/bin\/env bash\n/, '#!/usr/bin/env bash\n# Generated by `factory render`. Do not edit.\n') });
  // Static analysis CI jobs (opt-in: an analysis section): the generated script, its modules and job data, and this CI
  // system's file for the jobs (docs/ai-pipeline/analysis.md). GitLab's is listed in the root include below.
  for (const o of analysis.filter((x) => x.path)) out.push({ path: o.path, kind: 'file', content: preOpenCi(provider, o.path, o.content, config) });
  if (provider === 'gitlab-ci') {
    // The root include: the job templates first, then every job file.
    const files = out.map((o) => o.path).filter((p) => p.startsWith('.gitlab/')).sort((a, b) => Number(!a.endsWith('/factory-setup.yml')) - Number(!b.endsWith('/factory-setup.yml')) || a.localeCompare(b));
    out.push({ path: GITLAB_INCLUDE, kind: 'file', content: ['# Generated by `factory render`. Do not edit.', "# The factory's jobs, included from .gitlab-ci.yml. Redefine a job of the same name in .gitlab-ci.yml to", '# change it for your runners; GitLab merges your keys over these.', 'include:', ...files.map((f) => `  - local: ${f}`), ''].join('\n') });
    // The team's root file needs one include. A file with an include: list of its own cannot get a second
    // top-level key, so the block then only says what to add, and check reports it until it is there.
    const abs = path.join(root, GITLAB_ROOT);
    const theirs = stripBlock(readText(abs), 'hash') ?? '';
    const ownInclude = topLevelKeys(theirs).has('include');
    out.push({
      path: GITLAB_ROOT,
      kind: 'block',
      style: 'hash',
      content: ownInclude ? `# This file has its own include: list. Add this entry to it:\n#   - local: ${GITLAB_INCLUDE}` : `include:\n  - local: ${GITLAB_INCLUDE}`,
      verify: () => {
        const text = stripBlock(readText(abs), 'hash') ?? '';
        const problems = [];
        if (topLevelKeys(text).has('include') && !text.includes(GITLAB_INCLUDE)) problems.push(`its include: list does not name ${GITLAB_INCLUDE}, so the factory's jobs never run (add \`- local: ${GITLAB_INCLUDE}\`)`);
        const stages = /^stages\s*:\s*\n((?:[ \t]+-.*\n?)+)|^stages\s*:\s*\[([^\]]*)\]/m.exec(text);
        if (stages && !/(^|[\s,'"-])test(['"\s,]|$)/m.test(stages[1] ?? stages[2] ?? '')) problems.push('its stages: list has no `test` stage, which the factory\'s jobs use (add it, or redefine the jobs\' stage in .gitlab-ci.yml)');
        return problems;
      },
    });
  }
  return out;
}

