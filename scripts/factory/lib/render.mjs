// cannot live under .factory/ because another tool dictates the path (agent tool hooks, MCP config, agent
// files, CI workflows, instruction files). Three kinds of output keep the factory's part apart from the
// team's:
//   file   a whole file the factory owns (header says generated; never edited by hand)
//   block  a marked block inside a file the team also edits (AGENTS.md, .gitignore, ...)
//   json   the factory's entries inside a JSON file that cannot hold comments (.claude/settings.json, ...)
