const SHIM_CMD = 'node "$(git rev-parse --show-toplevel)/.factory/bin/factory.mjs"';
const gitHook = (lines) => `#!/usr/bin/env bash\n# Generated by \`factory render\`. Do not edit.\n${lines.join('\n')}\n`;

export function outputs(root, installRoot, pin = readPin(root), { providers: wantedProviders = null } = {}) {
  // The code host, tracker and CI system (.factory/config.json, else the origin remote; GitHub by default).
  const used = products(root);
  const providers = wantedProviders ?? [used.ci.provider];
  const t = (rel) => fs.readFileSync(path.join(installRoot, 'templates', rel), 'utf8');
  const tj = (rel) => JSON.parse(t(rel));
  const { features, tools } = pin;
  const out = [];
  const file = (p, content, extra = {}) => out.push({ path: p, kind: 'file', content, ...extra });

  // The shim: how every hook and person reaches the engine.
  file('.factory/bin/factory.mjs', t('shim/factory.mjs'), { executable: true });
  file('.factory/bin/factory', t('shim/factory'), { executable: true });
  file('.factory/bin/factory.cmd', t('shim/factory.cmd'));
  // `!bin/`: .NET, Java and Python templates ignore every `bin/` folder, which would drop the committed launcher.
  file('.factory/.gitignore', '# Generated by `factory render`. Machine-local state: runs, logs, the ticket cache, test stack state.\nstate/\n# The launcher is committed even where the repository ignores bin/ folders.\n!bin/\n');

  if (features.gitHooks) {
    const graphify = features.graphify ? ['command -v graphify >/dev/null 2>&1 && [ -z "${GRAPHIFY_BUILDING:-}" ] && ( ' + SHIM_CMD + ' graphify-build >/dev/null 2>&1 & ) >/dev/null 2>&1'] : [];
    const background = (event) => `command -v node >/dev/null 2>&1 && ${SHIM_CMD} git-hook ${event} || true`;
    file('.factory/githooks/pre-commit', gitHook(['# Lint the lines this commit touches with the repository\'s linters; keep the shared graphify cache. SKIP_LINT=1 skips the lint once.', 'command -v node >/dev/null 2>&1 || exit 0', `exec ${SHIM_CMD} git-hook pre-commit`]), { executable: true });
    file('.factory/githooks/post-commit', gitHook([...graphify, '# Pipeline stages in the background; never blocks git.', background('post-commit')]), { executable: true });
    file('.factory/githooks/post-merge', gitHook([...graphify, background('post-merge')]), { executable: true });
    // The graph follows the checked-out code: a branch switch (not a file checkout) and a rebase or amend.
    if (features.graphify) {
      file('.factory/githooks/post-checkout', gitHook(['[ "${3:-1}" = "0" ] && exit 0', ...graphify, 'exit 0']), { executable: true });
      file('.factory/githooks/post-rewrite', gitHook([...graphify, 'exit 0']), { executable: true });
    }
    file('.factory/githooks/pre-push', gitHook(['# Every stage\'s pre-push check (no LLM calls). Bypass feature verification once with FV_SKIP=1 git push.', 'command -v node >/dev/null 2>&1 || exit 0', `exec ${SHIM_CMD} git-hook pre-push`]), { executable: true });
  }

  const instructions = [t('instructions/factory.md'), features.graphify && t('instructions/graphify.md'), features.lsp && t('instructions/lsp.md'), features.demoVideo && t('instructions/demo-video.md')].filter(Boolean).map((s) => s.trim()).join('\n\n');
  // A file the factory creates (nothing of the team's outside the block) gets a top-level title inside the
  // block, so it passes Markdown linters (MD041: first line a top-level heading) and uninstall still removes
  // all of it. A file the team already has keeps its own title.
  // Decided by what precedes the block only, so the team may add text after it without the block changing.
  const mdBlock = (file) => {
    const text = readText(path.join(root, file)) ?? '';
    const at = text.indexOf(`${MARKERS.md[0]}\n`);
    const before = at >= 0 ? text.slice(0, at) : text;
    return { path: file, kind: 'block', style: 'md', content: before.trim() ? instructions : `# Agent instructions\n\n${instructions}` };
  };
  out.push(mdBlock('AGENTS.md'));

  const mcpLsp = { type: 'stdio', command: 'sh', args: ['-c', 'exec node "$(git rev-parse --show-toplevel)/.factory/bin/factory.mjs" lsp mcp'] };
  const mcpOutput = () => ({
    path: '.mcp.json',
    kind: 'json',
    expected: { lsp: mcpLsp },
    owned: (doc) => (doc?.mcpServers?.lsp ? { lsp: doc.mcpServers.lsp } : {}),
    apply: (doc) => ({ ...doc, mcpServers: { ...(doc.mcpServers ?? {}), lsp: mcpLsp } }),
    strip: (doc) => {
      const { lsp: _lsp, ...servers } = doc.mcpServers ?? {};
      const next = { ...doc, mcpServers: servers };
      if (!Object.keys(servers).length) delete next.mcpServers;
      return next;
    },
  });

  if (tools.includes('claude')) {
    out.push(mdBlock('CLAUDE.md'));
    const hooks = hooksOutput('.claude/settings.json', filterTemplate(tj('repo/.claude/settings.json'), features), features);
    if (features.lsp) {
      // Claude Code asks before using a project's MCP server unless the project enables it by name.
      const base = { ...hooks };
      hooks.expected = { hooks: base.expected, enabledMcpjsonServers: ['lsp'] };
      hooks.owned = (doc) => ({ hooks: base.owned(doc), enabledMcpjsonServers: (doc?.enabledMcpjsonServers ?? []).filter((s) => s === 'lsp') });
      hooks.apply = (doc) => ({ ...base.apply(doc), enabledMcpjsonServers: [...new Set([...(doc.enabledMcpjsonServers ?? []), 'lsp'])] });
      hooks.strip = (doc) => {
        const next = base.strip(doc);
        const servers = (next.enabledMcpjsonServers ?? []).filter((s) => s !== 'lsp');
        if (servers.length) next.enabledMcpjsonServers = servers;
        else delete next.enabledMcpjsonServers;
        return next;
      };
    }
    out.push(hooks);
  }
  if (features.lsp && (tools.includes('claude') || tools.includes('copilot') || tools.includes('cursor'))) out.push(mcpOutput());
  if (tools.includes('codex')) {
    out.push(hooksOutput('.codex/hooks.json', filterTemplate(tj('repo/.codex/hooks.json'), features), features));
    if (features.lsp) out.push({ path: '.codex/config.toml', kind: 'block', style: 'hash', content: t('repo/.codex/config.toml') });
  }
  if (tools.includes('gemini')) {
    out.push(mdBlock('GEMINI.md'));
    out.push(hooksOutput('.gemini/settings.json', filterTemplate(tj('repo/.gemini/settings.json'), features), features));
  }
  if (tools.includes('cursor')) file('.cursor/rules/factory.mdc', `---\ndescription: How this repository is worked on through the AI app factory (generated by factory render; do not edit)\nalwaysApply: true\n---\n\n${instructions}\n`);

  out.push(...agentOutputs(root, installRoot, pin));

  if (features.ci) for (const provider of providers) out.push(...ciOutputs(root, installRoot, provider, used, features));
  // graphify: only the semantic (LLM) cache is shared; the graph itself is rebuilt locally (`factory graphify-build`).
  if (features.graphify) out.push({ path: '.gitignore', kind: 'block', style: 'hash', content: ['# graphify: only the semantic (LLM) cache is committed; the rest is rebuilt by `factory graphify-build`.', 'graphify-out/*', '!graphify-out/cache/', 'graphify-out/cache/*', '!graphify-out/cache/semantic/', '# a graph built below the root (`graphify update <dir>`) is never committed', '*/**/graphify-out/', '*.graphify-bak'].join('\n') });
  // Code owners: the factory's governance (.factory/) and every file it generates need a review by the
  // owners named in factory.json (`owners`), so an agent's pull request cannot change how agents are governed
  // unnoticed. GitHub only *requires* that review when a branch rule asks for code-owner review, which a
  // private repository on a free plan cannot have; `factory doctor` reports which case this repository is in.
  const owners = (pin.owners ?? []).filter((o) => /^@[\w.-]+(\/[\w.-]+)?$|^[^@\s]+@[^@\s]+$/.test(o));
  if (owners.length && used.host.type !== 'azure-devops') {
    const existing = ['CODEOWNERS', 'docs/CODEOWNERS', ...(used.host.type === 'gitlab' ? ['.gitlab/CODEOWNERS'] : [])].find((f) => fs.existsSync(path.join(root, f)));
    const target = existing ?? (used.host.type === 'gitlab' ? '.gitlab/CODEOWNERS' : '.github/CODEOWNERS');
    const generated = [...new Set(out.map((o) => o.path))].filter((p) => !p.startsWith('.factory/') && !['.gitignore', '.gitattributes'].includes(p)).sort();
    const line = (p) => `/${p.replace(/ /g, '\\ ')} ${owners.join(' ')}`;
    out.push({ path: target, kind: 'block', style: 'hash', content: ['# The factory: governance, agents, hooks and generated files (owners from .factory/factory.json).', `/.factory/ ${owners.join(' ')}`, ...generated.map(line), line(target)].join('\n') });
  }
  out.push({ path: '.gitattributes', kind: 'block', style: 'hash', content: ['# Factory metrics are append-only logs: a union merge keeps every record across branches.', '.factory/metrics/*.jsonl merge=union', '# Generated by the factory: collapsed in pull request diffs.', '.factory/bin/** linguist-generated', '.factory/githooks/** linguist-generated', '# The launchers keep the line endings their shells need on every OS.', '.factory/bin/factory text eol=lf', '.factory/bin/factory.mjs text eol=lf', '.factory/bin/factory.cmd text eol=crlf', '.factory/githooks/** text eol=lf', '.factory/manifest.json linguist-generated', '.claude/agents/** linguist-generated', '.github/agents/** linguist-generated'].join('\n') });
  return out;
}

// ---- render, check, uninstall --------------------------------------------------------------------

const stable = (value) => JSON.stringify(value, (_k, v) => (v && typeof v === 'object' && !Array.isArray(v) ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => a.localeCompare(b))) : v));
const expectedHash = (o) => sha(o.kind === 'json' ? stable(o.expected) : o.content.trim());

function currentHash(root, o) {
  const abs = path.join(root, o.path);
  if (o.kind === 'file') {
    const text = readText(abs);
    return text == null ? null : sha(text.trim());
  }
  if (o.kind === 'block') {
    const block = extractBlock(readText(abs), o.style);
    return block == null ? null : sha(block);
  }
  if (!fs.existsSync(abs)) return null;
  return sha(stable(o.owned(readJson(abs))));
}

function writeOutput(root, o) {
  const abs = path.join(root, o.path);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  if (o.kind === 'file') {
    fs.writeFileSync(abs, o.content);
    if (o.executable) fs.chmodSync(abs, 0o755);
  } else if (o.kind === 'block') {
    fs.writeFileSync(abs, applyBlock(readText(abs), o.style, o.content));
  } else {
    fs.writeFileSync(abs, `${JSON.stringify(o.apply(readJson(abs)), null, 2)}\n`);
  }
}

function removeOutput(root, entryPath, kind, o) {
  const abs = path.join(root, entryPath);
  if (!fs.existsSync(abs)) return;
  if (kind === 'file') fs.rmSync(abs);
  else if (kind === 'block') {
    const rest = ['md', 'hash'].reduce((text, style) => stripBlock(text, style), readText(abs));
    if (rest.trim()) fs.writeFileSync(abs, rest);
    else fs.rmSync(abs);
  } else if (o) {
    const rest = o.strip(readJson(abs));
    if (Object.keys(rest).length) fs.writeFileSync(abs, `${JSON.stringify(rest, null, 2)}\n`);
    else fs.rmSync(abs);
  }
  // Leave no empty folders behind.
  for (let dir = path.dirname(abs); dir !== root && dir.startsWith(root) && fs.existsSync(dir) && !fs.readdirSync(dir).length; dir = path.dirname(dir)) fs.rmdirSync(dir);
}

// Every output the factory could write with all tools and features on: how to take back an entry that
// an earlier render wrote and the current settings no longer ask for.
const everyOutput = (root, installRoot) => new Map(outputs(root, installRoot, { tools: TOOLS, features: Object.fromEntries(Object.keys(FEATURE_DEFAULTS).map((k) => [k, true])) }, { providers: CI_PROVIDERS }).map((o) => [o.path, o]));

export const readManifest = (root) => readJson(path.join(root, MANIFEST), { files: {} });

export function render(root, installRoot, { version = null } = {}) {
  const pin = readPin(root);
  const wanted = outputs(root, installRoot, pin);
  const before = readManifest(root);
  const byPath = new Map(wanted.map((o) => [o.path, o]));
  // What an earlier render wrote and this one no longer wants (a feature turned off, a removed agent).
  const removed = Object.entries(before.files ?? {}).filter(([p]) => !byPath.has(p));
  const known = removed.length ? everyOutput(root, installRoot) : new Map();
  for (const [p, entry] of removed) removeOutput(root, p, entry.kind, known.get(p) ?? null);
  const written = [];
  for (const o of wanted) {
    if (currentHash(root, o) !== expectedHash(o)) {
      writeOutput(root, o);
      written.push(o.path);
    }
  }
  const manifest = { $comment: 'Generated by `factory render`: every file, block and JSON entry the factory owns in this repository. Do not edit.', version: version ?? before.version ?? null, files: Object.fromEntries(wanted.map((o) => [o.path, { kind: o.kind, sha: expectedHash(o) }]).sort(([a], [b]) => a.localeCompare(b))) };
  const text = `${JSON.stringify(manifest, null, 2)}\n`;
  if (readText(path.join(root, MANIFEST)) !== text) fs.writeFileSync(path.join(root, MANIFEST), text);
  return { written, removed: removed.map(([p]) => p), total: wanted.length };
}

// Drift: an output that is missing, was edited by hand, or is not what this engine version would write.
export function check(root, installRoot) {
  const wanted = outputs(root, installRoot, readPin(root));
  const manifest = readManifest(root);
  const problems = [];
  for (const o of wanted) {
    const current = currentHash(root, o);
    if (current == null) problems.push({ path: o.path, problem: 'missing' });
    else if (current !== expectedHash(o)) problems.push({ path: o.path, problem: manifest.files?.[o.path]?.sha === current ? 'outdated (the engine or .factory/ changed since the last render)' : 'edited by hand' });
  }
  for (const p of Object.keys(manifest.files ?? {})) if (!wanted.some((o) => o.path === p)) problems.push({ path: p, problem: 'no longer generated (render removes it)' });
  // What a block cannot do by itself (a team's own include: list must name the factory's file).
  for (const o of wanted) for (const problem of o.verify?.(root) ?? []) problems.push({ path: o.path, problem });
  // A generated file git ignores is never committed: teammates and CI would not have it.
  const files = wanted.filter((o) => o.kind === 'file' && !o.path.startsWith('.factory/state/')).map((o) => o.path);
  const ignored = spawnSync('git', ['check-ignore', '--no-index', '--stdin'], { cwd: root, input: files.join('\n'), encoding: 'utf8', timeout: 120_000 });
  if (ignored.status === 0) for (const p of ignored.stdout.split('\n').filter(Boolean)) problems.push({ path: p, problem: 'ignored by a .gitignore, so it is never committed (add a negation such as !path)' });
  return problems;
}

// Removes everything in the manifest. With `all`, .factory/ goes too. The app must build and pass its
// own tests afterwards: that is the proof it does not depend on the factory.
export function uninstall(root, installRoot, { all = false, dryRun = false } = {}) {
  const wanted = everyOutput(root, installRoot);
  const manifest = readManifest(root);
  const paths = Object.entries(manifest.files ?? {});
  if (!dryRun) {
    for (const [p, entry] of paths) removeOutput(root, p, entry.kind, wanted.get(p) ?? null);
    fs.rmSync(path.join(root, MANIFEST), { force: true });
    if (all) fs.rmSync(path.join(root, '.factory'), { recursive: true, force: true });
  }
  return { removed: paths.map(([p]) => p), all };
}
