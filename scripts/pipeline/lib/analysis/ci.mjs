// The analysis CI jobs (secret scan, dependency audit, ...), declared once as provider-neutral data
// ({ id, name, tools, required, when, fetchDepth, toolchain, timeoutSec }) and rendered for each CI system. Every job only
// calls one generated Node script (.factory/bin/analysis/ci.mjs), which installs the pinned, checksum-verified tools
// and runs them on the pull request against its base: no marketplace action for a scanner, no hosted service, no
// account, and the job gets no secret (read access to the repository only).
import fs from 'node:fs';
import path from 'node:path';
import { INSTALL_ROOT } from '../config.mjs';
import { resolveAnalysis } from './config.mjs';
import { isSecretTool } from './secrets.mjs';

export const CI_SCRIPT = '.factory/bin/analysis/ci.mjs';
export const CI_DATA = '.factory/bin/analysis/jobs.json';
export const GITHUB_WORKFLOW = '.github/workflows/factory-analysis.yml';
export const GITHUB_WORKFLOW_NAME = 'factory-analysis';
export const GITLAB_FILE = '.gitlab/ci/factory-analysis.yml';
export const AZURE_FILE = '.azure-pipelines/factory-analysis.yml';

// GitHub's own actions, pinned by commit (a tag can be moved; the workflow linters flag unpinned uses).
export const CHECKOUT_SHA = '34e114876b0b11c390a56381ad16ebd13914f8d5';
export const SETUP_NODE_SHA = '49933ea5288caeca8642d1e84afbd3f7d6820020';
const HEADER = '# Generated by `factory render` from the analysis CI jobs in .factory/config.json. Do not edit.\n';
const q = (s) => JSON.stringify(String(s));
const cmd = (job, base) => `node ${CI_SCRIPT} --job ${job.id} --base ${base}`;

// GitHub Actions: one workflow, one job per analysis job, on every pull request (so the review gate's expected-CI list
// and the default required checks pick each job up). actions/checkout and actions/setup-node are GitHub's own.
export function renderGithubActions(jobs) {
  if (!jobs.length) return null;
  const secrets = jobs.some((j) => j.secrets?.length);
  const lines = [HEADER.trimEnd(), `name: ${GITHUB_WORKFLOW_NAME}`, '', secrets ? '# Read access only. The open-source scanners get no secret; a commercial scanner\'s job gets its own token from the repository secrets (never on fork pull requests: GitHub withholds secrets there).' : '# Read access only: the scanners get no token and no secret.', 'permissions:', '  contents: read', '', 'on:', '  pull_request:', '', 'jobs:'];
  for (const j of jobs) {
    lines.push(`  ${j.id}:`, `    name: ${q(j.name)}`, '    runs-on: ubuntu-latest', `    timeout-minutes: ${Math.ceil(j.timeoutSec / 60)}`, '    steps:', `    - uses: actions/checkout@${CHECKOUT_SHA} # v4.3.1`, '      with:', `        fetch-depth: ${j.fetchDepth}`, '        persist-credentials: false', `    - uses: actions/setup-node@${SETUP_NODE_SHA} # v4.4.0`, '      with:', '        node-version: 20.x');
    if (j.toolchain) lines.push('    - name: "Toolchain (yours: .github/actions/factory-toolchain)"', "      if: hashFiles('.github/actions/factory-toolchain/action.yml') != ''", '      uses: ./.github/actions/factory-toolchain');
    // The base branch reaches the shell through the environment, never by template expansion into the script.
    lines.push(`    - name: ${q(j.name)}`, '      env:', '        BASE_REF: ${{ github.base_ref || github.event.repository.default_branch }}', ...(j.secrets ?? []).map((n) => `        ${n}: \${{ secrets.${n} }}`), `      run: FACTORY_CACHE_DIR="$RUNNER_TEMP/factory-cache" ${cmd(j, '"origin/$BASE_REF"')}`);
  }
  return `${lines.join('\n')}\n`;
}

// GitLab CI: a file the repository includes from its .gitlab-ci.yml; jobs run in merge request pipelines. A job is
// required when the project's "Pipelines must succeed" setting is on (doctor and the docs say so).
export function renderGitlabCi(jobs) {
  if (!jobs.length) return null;
  const lines = [HEADER.trimEnd(), '# Include it from .gitlab-ci.yml:  include: { local: .gitlab/ci/factory-analysis.yml }', ''];
  for (const j of jobs) {
    lines.push(
      `factory-analysis-${j.id}:`,
      `  # ${j.name}${j.required ? ' (required: keep "Pipelines must succeed" on)' : ''}`,
      '  stage: test',
      '  image: node:20',
      `  timeout: ${Math.ceil(j.timeoutSec / 60)}m`,
      '  rules:',
      "    - if: '$CI_PIPELINE_SOURCE == \"merge_request_event\"'",
      ...(j.required ? [] : ['      allow_failure: true']),
      '  variables:',
      `    GIT_DEPTH: "${j.fetchDepth}"`,
      '    FACTORY_CACHE_DIR: "$CI_PROJECT_DIR/.factory-cache"',
      '  script:',
      '    - git fetch --quiet origin "$CI_MERGE_REQUEST_TARGET_BRANCH_NAME"',
      `    - ${cmd(j, '"origin/$CI_MERGE_REQUEST_TARGET_BRANCH_NAME"')}`,
      '',
    );
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

// Azure Pipelines: a pipeline for pull request validation; a job is required through the branch policy's build
// validation (set outside YAML; the docs say how). NodeTool is a built-in Azure task.
export function renderAzurePipelines(jobs) {
  if (!jobs.length) return null;
  const lines = [HEADER.trimEnd(), 'trigger: none', 'pr:', '  branches:', '    include:', "    - '*'", '', 'jobs:'];
  for (const j of jobs) {
    lines.push(
      `- job: ${j.id.replace(/-/g, '_')}`,
      `  displayName: ${q(j.name)}`,
      `  timeoutInMinutes: ${Math.ceil(j.timeoutSec / 60)}`,
      ...(j.required ? [] : ['  continueOnError: true']),
      '  pool:',
      '    vmImage: ubuntu-latest',
      '  variables:',
      '    FACTORY_CACHE_DIR: $(Agent.TempDirectory)/factory-cache',
      '  steps:',
      '  - checkout: self',
      `    fetchDepth: ${j.fetchDepth}`,
      '    persistCredentials: false',
      '  - task: NodeTool@0',
      '    inputs:',
      "      versionSpec: '20.x'",
      '  - bash: |',
      '      base="$(System.PullRequest.TargetBranch)"',
      '      base="${base#refs/heads/}"',
      '      git fetch --quiet origin "$base"',
      `      ${cmd(j, '"origin/$base"')}`,
      `    displayName: ${q(j.name)}`,
      // Secret variables reach a script only when mapped (Azure's rule); a fork's build gets none.
      ...(j.secrets?.length ? ['    env:', ...j.secrets.map((n) => `      ${n}: $(${n})`)] : []),
    );
  }
  return `${lines.join('\n')}\n`;
}

// Jenkins, CircleCI and Bitbucket Pipelines read one definition file: the analysis jobs are snippets the generator puts
// in the factory's definition at its markers (render.mjs), each calling the generated script.
export function jenkinsSnippets(jobs) {
  if (!jobs.length) return null;
  return { 'factory:analysis': jobs.map((j) => [`stage(${q(j.name)}) {`, ...(j.secrets?.length ? ['  environment {', ...j.secrets.map((n) => `    ${n} = credentials('${n.toLowerCase().replace(/_/g, '-')}')`), '  }'] : []), `  options { timeout(time: ${j.timeoutSec}, unit: 'SECONDS') }`, `  steps { ${j.required ? '' : "catchError(buildResult: 'SUCCESS', stageResult: 'UNSTABLE') { "}sh 'FACTORY_CACHE_DIR="$WORKSPACE/.factory-cache" ${cmd(j, '"origin/${CHANGE_TARGET:-main}"')}'${j.required ? '' : ' }'} }`, '}'].join('\n')).join('\n') };
}
export function circleciSnippets(jobs) {
  if (!jobs.length) return null;
  return {
    'factory:analysis-jobs': jobs.map((j) => [`factory-analysis-${j.id}:`, '  executor: factory', '  steps:', '    - checkout', `    - run:`, `        name: ${q(j.name)}`, `        no_output_timeout: ${Math.ceil(j.timeoutSec / 60)}m`, `        command: FACTORY_CACHE_DIR="$HOME/.factory-cache" ${cmd(j, '"origin/main"')}`].join('\n')).join('\n'),
    'factory:analysis-workflow': jobs.map((j) => `- factory-analysis-${j.id}: { context: [factory] }`).join('\n'),
  };
}
export function bitbucketSnippets(jobs) {
  if (!jobs.length) return null;
  return { 'factory:analysis-steps': jobs.map((j) => [`- step:`, `    name: ${q(j.name)}`, `    max-time: ${Math.ceil(j.timeoutSec / 60)}`, '    script:', `      - git fetch --quiet origin "$BITBUCKET_PR_DESTINATION_BRANCH"`, `      - FACTORY_CACHE_DIR="$BITBUCKET_CLONE_DIR/.factory-cache" ${cmd(j, '"origin/$BITBUCKET_PR_DESTINATION_BRANCH"')}`].join('\n')).join('\n') };
}

export const RENDERERS = {
  'github-actions': { file: GITHUB_WORKFLOW, render: renderGithubActions },
  'gitlab-ci': { file: GITLAB_FILE, render: renderGitlabCi },
  'azure-pipelines': { file: AZURE_FILE, render: renderAzurePipelines },
  jenkins: { snippets: jenkinsSnippets },
  circleci: { snippets: circleciSnippets },
  'bitbucket-pipelines': { snippets: bitbucketSnippets },
};

// The data the CI script reads: each job's tools, with a pack's own parser module rewritten to the copy next to it and
// the factory's own rules rewritten to their rendered copy (MIT, the factory's: rendering them is not redistributing a
// third party's rules; pinned third-party rule sets are fetched by the CI script itself).
export function ciData(resolved, { installRoot = INSTALL_ROOT } = {}) {
  const jobs = resolved?.ci?.jobs ?? [];
  const tools = {};
  const modules = {};
  const rules = {};
  for (const j of jobs) {
    for (const id of j.tools) {
      const t = resolved.tools.get(id);
      if (!t || tools[id]) continue;
      let parse = t.parse;
      if (parse.startsWith('module:')) {
        modules[`.factory/bin/analysis/parsers/${id}.mjs`] = parse.slice(7);
        parse = `module:./parsers/${id}.mjs`;
      }
      const sources = (t.rules ?? []).map((src) => {
        if (!src.builtin) return src;
        const dirs = (src.include.length ? src.include : ['.']).map((inc) => {
          const from = path.join(installRoot, 'packs', 'security', 'rules', src.builtin, inc);
          const to = `.factory/bin/analysis/rules/${src.builtin}/${inc}`;
          for (const f of fs.existsSync(from) ? fs.readdirSync(from).filter((n) => /\.ya?ml$/.test(n)) : []) rules[`${to}/${f}`] = path.join(from, f);
          return to;
        });
        return { ...src, builtin: null, dirs };
      });
      tools[id] = { run: t.run, parse, output: t.output, scope: t.scope ?? 'repo', ...(isSecretTool(t) ? { secretValues: true } : {}), baseline: t.baseline, block: t.block, timeoutSec: t.timeoutSec, env: t.env, install: t.install, rules: sources, rulesArg: t.rulesArg, validateRule: t.validateRule, prepare: t.prepare, when: t.when, okExit: t.okExit, data: t.data, errorPattern: t.errorPattern, missingPattern: t.missingPattern, ruleFilter: t.ruleFilter, needsRules: t.needsRules, ...(t.severity ? { severity: t.severity } : {}), ...(t.commercial ? { commercial: { vendor: t.commercial.vendor, mode: t.commercial.mode } } : {}), ...(t.submitOnly ? { submitOnly: true } : {}) };
    }
  }
  return { data: { $comment: 'Generated by `factory render`. Do not edit.', jobs, tools, vars: resolved?.vars ?? {} }, modules, rules };
}

// Every file the CI jobs need in the repository: the script, its parsers, baseline and decision (copied from the engine: they use
// only Node's own modules), the job data, and the CI system's own file. Returns [{ path, content }].
export function ciOutputs(config, { provider = 'github-actions', installRoot = INSTALL_ROOT, resolved = resolveAnalysis(config, { installRoot }) } = {}) {
  const jobs = resolved?.ci?.jobs ?? [];
  if (!jobs.length) return [];
  const read = (rel) => fs.readFileSync(path.join(installRoot, rel), 'utf8');
  const gen = (text) => `// Generated by \`factory render\`. Do not edit.\n${text}`;
  const { data, modules, rules } = ciData(resolved, { installRoot });
  const out = [
    { path: CI_SCRIPT, content: gen(read('templates/analysis/ci.mjs')) },
    { path: '.factory/bin/analysis/parsers.mjs', content: gen(read('scripts/pipeline/lib/analysis/parsers.mjs')) },
    { path: '.factory/bin/analysis/baseline.mjs', content: gen(read('scripts/pipeline/lib/analysis/baseline.mjs')) },
    { path: '.factory/bin/analysis/decide.mjs', content: gen(read('scripts/pipeline/lib/analysis/decide.mjs')) },
    { path: '.factory/bin/analysis/commercial.mjs', content: gen(read('scripts/pipeline/lib/analysis/commercial.mjs')) },
    { path: '.factory/bin/analysis/fetch.mjs', content: gen(read('scripts/pipeline/lib/analysis/fetch.mjs')) },
    // The redaction boundary the parsers use (a secret scanner's matched values are remembered as hashes, never kept).
    { path: '.factory/bin/redact.mjs', content: gen(read('scripts/pipeline/lib/redact.mjs')) },
    ...Object.entries(rules).map(([p, src]) => ({ path: p, content: fs.readFileSync(src, 'utf8') })),
    { path: CI_DATA, content: `${JSON.stringify(data, null, 2)}\n` },
    ...Object.entries(modules).map(([p, src]) => ({ path: p, content: gen(fs.readFileSync(src, 'utf8')) })),
  ];
  const r = RENDERERS[provider];
  if (r?.render) out.push({ path: r.file, content: r.render(jobs) });
  if (r?.snippets) for (const [marker, content] of Object.entries(r.snippets(jobs) ?? {})) out.push({ snippet: marker, content });
  return out;
}

// The check names the CI system reports for the jobs (GitHub: the job names), for the review gate and branch rules.
// A commercial scanner in server mode adds its own check on the head (the vendor's name, or analysis.commercial.check).
export const ciCheckNames = (resolved) => [...(resolved?.ci?.jobs ?? []).filter((j) => j.required).map((j) => j.name), ...(resolved?.commercial ?? []).filter((e) => e.mode === 'server').map((e) => e.check ?? e.tool?.commercial?.check).filter(Boolean)];

// The review gate waits for the analysis jobs before anything calls a head green or auto-merges it. Without settings
// it derives the expected workflows and required checks from the workflow files, which include the rendered analysis
// workflow; a repository that lists them by hand (`implement.reviewGate.ci.expected`, `requiredChecks`) gets the
// analysis workflow and its required job names added, and cannot ignore it. Mutates and returns `config`.
export function withAnalysisGate(config, resolved = null) {
  let a = resolved;
  try {
    a ??= resolveAnalysis(config);
  } catch {
    return config;
  }
  const jobs = a?.ci?.jobs ?? [];
  if (!jobs.length || !config.implement?.reviewGate) return config;
  const gate = config.implement.reviewGate;
  if (gate.ci) {
    if (Array.isArray(gate.ci.expected) && !gate.ci.expected.includes(GITHUB_WORKFLOW)) gate.ci.expected = [...gate.ci.expected, GITHUB_WORKFLOW];
    if (Array.isArray(gate.ci.ignore)) gate.ci.ignore = gate.ci.ignore.filter((p) => p !== GITHUB_WORKFLOW);
    if (Array.isArray(gate.ci.ignoreNames)) gate.ci.ignoreNames = gate.ci.ignoreNames.filter((n) => n !== GITHUB_WORKFLOW_NAME);
  }
  if (Array.isArray(gate.requiredChecks)) gate.requiredChecks = [...new Set([...gate.requiredChecks, ...ciCheckNames(a)])];
  return config;
}
