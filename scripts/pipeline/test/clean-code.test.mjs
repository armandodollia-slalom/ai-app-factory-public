// Council r1 (opus, plugin copy): the plugin serves skills/ as they are, so the clean-code skill's file carries the
// included list itself, kept in step with the council skill it comes from.
test('the clean-code skill file carries each included list, the same as its source skill\'s', async () => {
  const { syncIncludes } = await import('../lib/clean-code.mjs');
  const file = path.join(INSTALL, 'skills/clean-code/SKILL.md');
  const text = fs.readFileSync(file, 'utf8');
  assert.equal(syncIncludes(text), text, 'stale: run node scripts/pipeline/lib/clean-code.mjs --write');
  assert.doesNotMatch(text, /<!-- include: [^\n]*-->\n(?!- )/, 'every include is followed by its list');
  // A list that changed in the council skill makes the copy stale.
  const council = path.join(INSTALL, 'skills/council/SKILL.md');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'skills-'));
  fs.mkdirSync(path.join(dir, 'council'));
  fs.writeFileSync(path.join(dir, 'council/SKILL.md'), fs.readFileSync(council, 'utf8').replace('- it tests a getter, a constructor or a constant;\n', ''));
  assert.notEqual(syncIncludes(text, dir), text);
  fs.rmSync(dir, { recursive: true, force: true });
});

// Council r3 (cc-21): one folder and one time window for the language-server call log. The implement stage's adapter
// (lsp.calls) and the search trace (searchCalls) read the same log and pick the same calls: the agent's, within a
// second of the run; outside a git checkout, none.
test('cc-21: the language-server call log has one folder and one time window, for both of its readers', async (t) => {
  const { lspAdapter, callsFile } = await import('../../implement/lib/lsp.mjs');
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'cc21-')));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  spawnSync('git', ['init', '-q', '-b', 'main'], { cwd: root });
  const from = Date.parse('2026-11-24T12:00:00.000Z');
  const to = from + 60_000;
  const at = (ms) => new Date(ms).toISOString();
  const call = (agent, ms, symbol) => ({ ts: at(ms), agent, member: null, tool: 'mcp__lsp__lsp_find_references', file: 'a.js', symbol });
  const log = [call('implementer', from - 1001, 'early'), call('implementer', from - 1000, 'edge-start'), call('implementer', from + 5, 'inside'), call('reviewer', from + 6, 'other-agent'), call('implementer', to + 1000, 'edge-end'), call('implementer', to + 1001, 'late')];
  assert.equal(callsFile(root), path.join(root, '.git', 'lsp', 'calls.jsonl'));
  fs.mkdirSync(path.dirname(callsFile(root)), { recursive: true });
  fs.writeFileSync(callsFile(root), log.map((c) => JSON.stringify(c)).join('\n') + '\n');
  const symbols = (calls) => calls.map((c) => c.symbol);
  const expected = ['edge-start', 'inside', 'edge-end'];
  assert.deepEqual(symbols(lspAdapter({ root }).calls(root, 'implementer', from, to)), expected);
  assert.deepEqual(symbols(searchCalls(root, { agent: 'implementer', from, to })), expected);
  const outside = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'cc21-nogit-')));
  t.after(() => fs.rmSync(outside, { recursive: true, force: true }));
  assert.deepEqual([callsFile(outside), lspAdapter({ root }).calls(outside, 'implementer', from, to), searchCalls(outside, { from, to })], [null, [], []]);
});
